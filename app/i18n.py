def month_name(n):
    """The localized name of month n (1-12)."""
    names = MONTHS.get(_current, MONTHS['en'])
    return names[n] if 1 <= n <= 12 else ''


def month_label(n):
    """Localized month name with its number, e.g. 'אוגוסט (8)'."""
    return f'{month_name(n)} ({n})'
